// apps/web/bin/master_upsert_sql.ts
//
// Builds deploy/seed/master_upsert.sql, which bootstrap.sh applies on every
// web boot. Pure so the statements can be run against a test database.

/** Retired sources the seed must not re-create (0045 dropped synthetic). */
const EXCLUDED_SOURCES = new Set(['synthetic']);

export interface SeedWatershed {
  code: string;
  slug: string;
  name: string;
  name_kana: string | null;
  kind: string;
  ndi_code: string | null;
  boundary: string | null; // hex EWKB
  area_km2: string | null;
}
export interface SeedDam {
  slug: string;
  name: string;
  name_kana: string | null;
  pref_code: string;
  manager: string | null;
  type: string | null;
  height_m: string | null;
  total_capacity_m3: string | null;
  effective_capacity_m3: string | null;
  flood_capacity_m3: string | null;
  active_capacity_m3: string | null;
  completed_year: number | null;
  construction_start_year: number | null;
  purposes: string | null;
  crest_length_m: string | null;
  embankment_volume_m3: string | null;
  watershed_area_km2: string | null;
  reservoir_area_km2: string | null;
  left_bank_location: string | null;
  main_contractor: string | null;
  redevelopment_status: string | null;
  elevation_m: number | null;
  image_url: string | null;
  location: string; // hex EWKB
  external_ids: Record<string, string>;
}
export interface SeedSource {
  source_id: string;
  description: string;
  priority: number;
  active: boolean;
}

function quote(v: string | number | boolean | null | undefined): string {
  if (v == null) return 'NULL';
  if (typeof v === 'boolean') return v ? 'TRUE' : 'FALSE';
  if (typeof v === 'number') return String(v);
  // SQL string literal: double single quotes inside.
  return `'${String(v).replace(/'/g, "''")}'`;
}
function jsonbLit(o: object | null): string {
  if (o == null) return 'NULL';
  return `'${JSON.stringify(o).replace(/'/g, "''")}'::jsonb`;
}
function geoLit(hex: string | null): string {
  // Stored as `BYTEA`-shaped hex of EWKB. We re-cast on prod via ::geography.
  if (hex == null) return 'NULL';
  return `'${hex}'::geography`;
}

export function buildMasterUpsertSql({
  sources,
  watersheds,
  dams,
}: {
  sources: SeedSource[];
  watersheds: SeedWatershed[];
  dams: SeedDam[];
}): string {
  const lines: string[] = [];
  lines.push('-- Non-destructive master upsert. Generated by generate_master_upsert.ts');
  lines.push('-- Safe to re-run; never TRUNCATEs observations / raw_snapshots / match_review.');
  lines.push('BEGIN;');
  lines.push('SET LOCAL search_path = public;');
  lines.push('');

  // ─── source_priorities ───────────────────────────────────────────────
  lines.push('-- source_priorities: insert missing rows only. Migrations and ingest tasks own');
  lines.push('-- the live values; a stale snapshot must not overwrite them.');
  for (const s of sources.filter((x) => !EXCLUDED_SOURCES.has(x.source_id))) {
    lines.push(
      `INSERT INTO source_priorities (source_id, description, priority, active) VALUES (${quote(s.source_id)}, ${quote(s.description)}, ${quote(s.priority)}, ${quote(s.active)}) ON CONFLICT (source_id) DO NOTHING;`,
    );
  }
  lines.push('');

  // ─── watersheds ──────────────────────────────────────────────────────
  // Stage in a temp table, then upsert by code.
  lines.push(
    'CREATE TEMP TABLE _seed_watersheds (LIKE public.watersheds INCLUDING DEFAULTS) ON COMMIT DROP;',
  );
  lines.push(
    'ALTER TABLE _seed_watersheds DROP COLUMN IF EXISTS id;', // we want fresh ids on insert; matches by code
  );
  for (const w of watersheds) {
    lines.push(
      `INSERT INTO _seed_watersheds (code, slug, name, name_kana, kind, ndi_code, boundary, area_km2) VALUES (${quote(w.code)}, ${quote(w.slug)}, ${quote(w.name)}, ${quote(w.name_kana)}, ${quote(w.kind)}, ${quote(w.ndi_code)}, ${geoLit(w.boundary)}, ${quote(w.area_km2)});`,
    );
  }
  lines.push('');
  lines.push('-- UPSERT into live watersheds, matching by code (existing unique constraint).');
  lines.push('UPDATE public.watersheds w SET');
  lines.push('  slug      = s.slug,');
  lines.push('  name      = s.name,');
  lines.push('  name_kana = s.name_kana,');
  lines.push('  kind      = s.kind,');
  lines.push('  ndi_code  = s.ndi_code,');
  lines.push('  boundary  = s.boundary,');
  lines.push('  area_km2  = s.area_km2');
  lines.push('FROM _seed_watersheds s');
  lines.push('WHERE w.code = s.code;');
  lines.push('');
  lines.push(
    `INSERT INTO public.watersheds (code, slug, name, name_kana, kind, ndi_code, boundary, area_km2)
     SELECT s.code, s.slug, s.name, s.name_kana, s.kind, s.ndi_code, s.boundary, s.area_km2
     FROM _seed_watersheds s
     WHERE NOT EXISTS (SELECT 1 FROM public.watersheds w WHERE w.code = s.code);`,
  );
  lines.push('');

  // ─── dams ────────────────────────────────────────────────────────────
  lines.push('CREATE TEMP TABLE _seed_dams (LIKE public.dams INCLUDING DEFAULTS) ON COMMIT DROP;');
  lines.push('ALTER TABLE _seed_dams DROP COLUMN IF EXISTS id;');
  // Insert all rows. We deliberately skip river_id / watershed_id because
  // those FKs reference local IDs not prod IDs; bootstrap can re-run a
  // join-by-code pass if needed.
  for (const d of dams) {
    lines.push(
      `INSERT INTO _seed_dams (slug, name, name_kana, pref_code, manager, type,
        height_m, total_capacity_m3, effective_capacity_m3, flood_capacity_m3, active_capacity_m3,
        completed_year, construction_start_year, purposes, crest_length_m, embankment_volume_m3,
        watershed_area_km2, reservoir_area_km2, left_bank_location, main_contractor, redevelopment_status,
        elevation_m, image_url, location, external_ids) VALUES (${quote(d.slug)}, ${quote(d.name)}, ${quote(d.name_kana)}, ${quote(d.pref_code)}, ${quote(d.manager)}, ${quote(d.type)},
        ${quote(d.height_m)}, ${quote(d.total_capacity_m3)}, ${quote(d.effective_capacity_m3)}, ${quote(d.flood_capacity_m3)}, ${quote(d.active_capacity_m3)},
        ${quote(d.completed_year)}, ${quote(d.construction_start_year)}, ${quote(d.purposes)}, ${quote(d.crest_length_m)}, ${quote(d.embankment_volume_m3)},
        ${quote(d.watershed_area_km2)}, ${quote(d.reservoir_area_km2)}, ${quote(d.left_bank_location)}, ${quote(d.main_contractor)}, ${quote(d.redevelopment_status)},
        ${quote(d.elevation_m)}, ${quote(d.image_url)}, ${geoLit(d.location)}, ${jsonbLit(d.external_ids)});`,
    );
  }
  lines.push('');

  // UPDATE matching by NDI external_id — the natural key for our master,
  // enforced by `dams_ext_ndi_uniq`. Prod wins: the seed is a snapshot of a
  // local DB, and prod's rows move on without it (master:refresh:damnet
  // re-stamps and re-specs monthly, ingest tasks bind their stations, the
  // slug repair renames, migrations fix data). Until #54 this was seed-wins
  // and rolled all of that back on every deploy; a snapshot's source stamps
  // also point at rows later found wrong (#57), so external_ids are left
  // alone too. Only a blank elevation / image is filled.
  lines.push(`-- UPDATE dams matched by external_ids->>'ndi'. Prod wins; see generator.`);
  lines.push('UPDATE public.dams d SET');
  lines.push('  elevation_m  = COALESCE(d.elevation_m, s.elevation_m),');
  lines.push('  image_url    = COALESCE(d.image_url, s.image_url),');
  lines.push('  updated_at   = NOW()');
  lines.push('FROM _seed_dams s');
  lines.push(`WHERE s.external_ids ? 'ndi' AND d.external_ids->>'ndi' = s.external_ids->>'ndi';`);
  lines.push('');

  // INSERT new dams (those not yet in prod).
  lines.push('-- INSERT brand-new dams (those in seed without a matching prod row by NDI).');
  lines.push(
    `INSERT INTO public.dams (
      slug, name, name_kana, pref_code, manager, type,
      height_m, total_capacity_m3, effective_capacity_m3, flood_capacity_m3, active_capacity_m3,
      completed_year, construction_start_year, purposes, crest_length_m, embankment_volume_m3,
      watershed_area_km2, reservoir_area_km2, left_bank_location, main_contractor, redevelopment_status,
      elevation_m, image_url, location, external_ids)
     SELECT
       s.slug, s.name, s.name_kana, s.pref_code, s.manager, s.type,
       s.height_m, s.total_capacity_m3, s.effective_capacity_m3, s.flood_capacity_m3, s.active_capacity_m3,
       s.completed_year, s.construction_start_year, s.purposes, s.crest_length_m, s.embankment_volume_m3,
       s.watershed_area_km2, s.reservoir_area_km2, s.left_bank_location, s.main_contractor, s.redevelopment_status,
       s.elevation_m, s.image_url, s.location, jsonb_strip_nulls(jsonb_build_object('ndi', s.external_ids->>'ndi'))
     FROM _seed_dams s
     WHERE NOT EXISTS (
       SELECT 1 FROM public.dams d
       WHERE s.external_ids ? 'ndi' AND d.external_ids->>'ndi' = s.external_ids->>'ndi'
     )
     ON CONFLICT (slug) DO NOTHING;`,
  );
  lines.push('');

  // watershed_id / river_id are deliberately not patched here — those FK
  // links are set by the NDI import on prod, keyed by external_ids->>'ndi'.
  // The seed's local-only IDs would just clobber correct prod values.

  lines.push('COMMIT;');
  lines.push('');

  return lines.join('\n');
}
